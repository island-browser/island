#!/usr/bin/env python3
"""Generate src/main/query_display_ranges.h, the allowlist of non-ASCII code points that the
address field may show for a search query.

Rule: a non-ASCII code point is shown only when its Unicode general category is L*, M*, N* or Zs
(letters, marks, numbers, space separators). Ranges are then removed for the explicit exclusions
(modifier letters U+02B0..U+02FF, which hold U+02D0; modifier letters U+A700..U+A71F; fullwidth
forms U+FF00..U+FFEF). ASCII is decided by the caller.

Regenerate after a Unicode upgrade with:
    python3 scripts/gen_query_display_ranges.py
The table is written from the Python interpreter's unicodedata module; its Unicode version is
printed in the generated header. No ICU is used.
"""

import sys
import unicodedata
from pathlib import Path

OUTPUT = Path(__file__).resolve().parent.parent / "src" / "main" / "query_display_ranges.h"
MAX_CODE_POINT = 0x10FFFF
EXCLUDED = [
    (0x02B0, 0x02FF),  # modifier letters, including U+02D0 MODIFIER LETTER TRIANGULAR COLON
    (0xA700, 0xA71F),  # modifier letters (tone marks, dot-vertical bar)
    (0xFF00, 0xFFEF),  # fullwidth and halfwidth forms
]
ALLOWED_PREFIXES = ("L", "M", "N")
ALLOWED_CATEGORIES = {"Zs"}
RANGES_PER_LINE = 4


def is_allowed(code_point: int) -> bool:
    category = unicodedata.category(chr(code_point))
    return category[0] in ALLOWED_PREFIXES or category in ALLOWED_CATEGORIES


def allowed_ranges() -> list[tuple[int, int]]:
    ranges: list[tuple[int, int]] = []
    start = None
    for code_point in range(0x80, MAX_CODE_POINT + 1):
        allowed = is_allowed(code_point) and not any(
            first <= code_point <= last for first, last in EXCLUDED
        )
        if allowed and start is None:
            start = code_point
        elif not allowed and start is not None:
            ranges.append((start, code_point - 1))
            start = None
    if start is not None:
        ranges.append((start, MAX_CODE_POINT))
    return ranges


def render(ranges: list[tuple[int, int]]) -> str:
    version = unicodedata.unidata_version
    lines = [
        "// Generated by scripts/gen_query_display_ranges.py from Unicode "
        f"{version}. Do not edit by hand.",
        "//",
        "// Non-ASCII code points an address-field query may show: general categories L*, M*, N* and",
        "// Zs, minus modifier letters U+02B0..U+02FF and U+A700..U+A71F and fullwidth forms",
        "// U+FF00..U+FFEF. Every other non-ASCII code point (punctuation, symbols, format and control",
        "// characters, separators) makes the full address show instead.",
        "",
        "#ifndef ISLAND_QUERY_DISPLAY_RANGES_H_",
        "#define ISLAND_QUERY_DISPLAY_RANGES_H_",
        "",
        "#include <array>",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "namespace island {",
        "",
        "struct CodePointRange {",
        "    std::uint32_t first;",
        "    std::uint32_t last;",
        "};",
        "",
        "// Sorted, non-overlapping, inclusive ranges.",
        f"inline constexpr std::size_t kDisplayShownNonAsciiRangeCount = {len(ranges)};",
        "inline constexpr std::array<CodePointRange, kDisplayShownNonAsciiRangeCount>",
        "    kDisplayShownNonAsciiRanges = {{",
    ]
    for index in range(0, len(ranges), RANGES_PER_LINE):
        chunk = ranges[index : index + RANGES_PER_LINE]
        body = ", ".join(f"{{0x{first:05X}, 0x{last:05X}}}" for first, last in chunk)
        lines.append(f"        {body},")
    lines += [
        "    }};",
        "",
        "}  // namespace island",
        "",
        "#endif  // ISLAND_QUERY_DISPLAY_RANGES_H_",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    OUTPUT.write_text(render(allowed_ranges()), encoding="utf-8")
    print(f"wrote {OUTPUT}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
